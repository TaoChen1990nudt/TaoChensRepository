#pragma once

#include <cmath>

//==============================================================================
/** Phase 104 — 削波不是读数，是事件。

    Phase 103 给每一种「meter」立了一套动作：**发布取大、按速率回落、读完消费**。
    那三条对增益衰减成立，是因为它记的是一个**状态**——「这一个插槽此刻在压多少」，
    而状态会自己消失，所以读数也该自己消失。

    削波不是那种东西。它记的是一个**事件**：「这块缓冲里有样本越过了满刻度」。
    事件不会因为没人看而变得没发生，所以这个读数**不回落、不消费、不自己消失**——
    它只在两个时刻清零：用户点了那盏灯，或者这个会话被换掉了。

    这个区别不是文风。一秒钟里可能只有一次削波，发生在某个瞬态的第一个周期上；
    按 24 dB/s 回落的读数会在用户抬头之前把它抹平，于是「刚才那声破音是我还是
    机器」这个问题永远没有答案。反过来，一个永不回落的读数如果**忘了**清，它就会
    变成装饰——所以清除必须有一个用户按得到的入口，而不是「下次播放时自己好」。

    还有一条边界值得写死：**满刻度不是削波**。0 dBFS（|x| == 1.0）是这条尺子的
    最后一格，不是越过它。把 1.0 算成削波，等于让每一个规规矩矩推到 0 dB 的混音
    常亮——灯一旦永远亮着，它就不再报告任何东西。
*/
namespace atomic
{
namespace overload
{

/** 满刻度。0 dBFS 就是它。 */
inline constexpr float fullScale = 1.0f;

/** 这个样本（或这一块的峰值）爆了吗？

    判据是 **严格大于**，理由见上面最后一段。

    取绝对值：削波是「幅度超过满刻度」，负半周的 -1.5 V 和正半周的 +1.5 V 是
    同一件事。引擎喂进来的是 `getMagnitude()`（已经取过绝对值），所以这里再取一次
    是多余的——这一句是给**下一个调用者**写的：把有符号的样本直接传进来是一个太
    容易犯的错，而它的表现是「灯永远不亮」，比一个明显的错更难发现。 */
inline bool isClipped (float sampleOrPeak) noexcept
{
    return std::abs (sampleOrPeak) > fullScale;
}

} // namespace overload
} // namespace atomic
